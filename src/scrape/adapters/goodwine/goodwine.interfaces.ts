/**
 * The snapshot field a Goodwine specification label fills.
 */
export enum GoodwineSpecField {
  /**
   * Country of origin (`Країна`).
   */
  COUNTRY = 'country',
  /**
   * Bottle volume (`Ємність`, `Об'єм`).
   */
  VOLUME = 'volume',
  /**
   * Alcohol by volume (`Міцність, %`).
   */
  ABV = 'abv',
  /**
   * Whisky type (`Тип віскі`).
   */
  WHISKY_TYPE = 'whiskyType',
  /**
   * Brand (`Торгова марка`).
   */
  BRAND = 'brand',
}
