/**
 * The snapshot field a Fozzy Shop characteristics label fills.
 */
export enum FozzySpecField {
  /**
   * Country of origin (`Країна`).
   */
  COUNTRY = 'country',
  /**
   * Brand (`Бренд`).
   */
  BRAND = 'brand',
  /**
   * Alcohol by volume (`Міцність алкоголю, %`).
   */
  ABV = 'abv',
  /**
   * Age statement (`Термін витримки, років`).
   */
  AGE = 'age',
  /**
   * Whisky type (`Тип`).
   */
  WHISKY_TYPE = 'whiskyType',
}
